const drain = (h) => { const o = []; while (h.size > 0) o.push(h.pop()); return o; };

function runOps(ops) { // ops: ['push', [key, id]] | ['pop'], 비교는 key 만(동률 순서가 python 과 같아야 함)
  const h = new MinHeap((a, b) => a[0] - b[0]);
  const out = [];
  for (const op of ops) {
    if (op[0] === 'push') h.push(op[1]);
    else out.push(h.pop() ?? null);
  }
  return out;
}

test('MinHeap: 튜플 정렬 결과가 python heapq 와 같다(미리 계산)', () => {
  for (const c of DATA.tupleCases) {
    const h = new MinHeap();
    for (const x of c.items) h.push(x);
    assert.deepEqual(drain(h), c.expected);
    assert.deepEqual(drain(new MinHeap(compareTuples, c.items)), c.expected); // heapify 경로
  }
});

test('MinHeap: 동률 비교 함수에서도 pop 순서가 python heapq 와 같다(미리 계산)', () => {
  assert.deepEqual(runOps(DATA.tieOps), DATA.tieExpected);
});

test('MinHeap: python 이 있으면 실제 heapq 와 비교', (t) => {
  const py = findPython();
  if (!py) return t.skip('python3 없음');
  const script = [
    'import sys, json, heapq',
    'req = json.load(sys.stdin)',
    'class K:',
    '    def __init__(s, k, i): s.k = k; s.i = i',
    '    def __lt__(s, o): return s.k < o.k',
    'res = {"tuples": [], "ties": []}',
    'for c in req["tupleCases"]:',
    '    h = []',
    '    for x in c["items"]: heapq.heappush(h, tuple(x))',
    '    res["tuples"].append([list(heapq.heappop(h)) for _ in range(len(h))])',
    'h = []',
    'for op in req["tieOps"]:',
    '    if op[0] == "push": heapq.heappush(h, K(*op[1]))',
    '    else:',
    '        if h: x = heapq.heappop(h); res["ties"].append([x.k, x.i])',
    '        else: res["ties"].append(None)',
    'print(json.dumps(res))',
  ].join('\n');
  const r = runCommand(py, ['-c', script], { input: JSON.stringify(DATA), env: { PYTHONUTF8: '1', PYTHONIOENCODING: 'utf-8' } });
  assert.equal(r.status, 0, r.stderr);
  const out = JSON.parse(r.stdout);
  DATA.tupleCases.forEach((c, i) => {
    const h = new MinHeap();
    for (const x of c.items) h.push(x);
    assert.deepEqual(drain(h), out.tuples[i]);
  });
  assert.deepEqual(runOps(DATA.tieOps), out.ties);
});

test('MinHeap: size·peek·빈 힙 pop, 사용자 비교 함수', () => {
  const h = new MinHeap((a, b) => b - a); // 최대 힙처럼 사용
  assert.equal(h.size, 0);
  assert.equal(h.pop(), undefined);
  assert.equal(h.peek(), undefined);
  [3, 9, 1, 7].forEach((x) => h.push(x));
  assert.equal(h.size, 4);
  assert.equal(h.peek(), 9);
  assert.deepEqual(drain(h), [9, 7, 3, 1]);
});

test('compareTuples: 요소 순서·길이·문자열 코드포인트·형식 불일치', () => {
  assert.ok(compareTuples([1, 'b'], [1, 'c']) < 0);
  assert.ok(compareTuples([1, 2], [1, 2, 0]) < 0);
  assert.equal(compareTuples([1, 2], [1, 2]), 0);
  assert.ok(compareTuples([2], [1, 9]) > 0);
  assert.ok(compareTuples([[1, 2], 'x'], [[1, 3], 'a']) < 0);
  assert.ok(compareTuples([true], [2]) < 0);
  assert.ok(compareTuples([String.fromCodePoint(0xe000)], [String.fromCodePoint(0x1f600)]) < 0);
  assert.throws(() => compareTuples([1], ['a']), TypeError);
});
